def emit_font(size, ref, glyphs, src):
    sym = 'ob_icons_%d' % size
    guard = size_guard(size)
    bitmap, dscs = bytearray(), []
    for (macro, rid), (adv, bw, bh, ox, oy, rows) in zip(PANEL_ICONS, glyphs):
        dscs.append((len(bitmap), adv, bw, bh, ox, oy, rid))
        bitmap += pack4(rows)
    L = ['/* GENERATED by tools/gen_icons.py from tools/icons/openbridge-map.json and the Figma',
         ' * export of the "OpenBridge Icon Pack" - DO NOT EDIT; run  python tools/gen_icons.py',
         ' * OpenBridge icon trial: this file belongs to the trial (see ICONS-TRIAL.md).',
         ' *',
         ' * Size: %d px   Bpp: 4   Glyphs: %d   Code points: U+%04X..U+%04X (Private Use Area)'
         % (size, len(dscs), PUA_BASE, PUA_BASE + len(dscs) - 1),
         ' *'] + licence_block(src) + [' */']
    L += ['#ifdef LV_LVGL_H_INCLUDE_SIMPLE', '    #include "lvgl.h"', '#else',
          '    #include "lvgl/lvgl.h"', '#endif', '']
    if guard:
        L += ['/* Only the board(s) whose font roles use this size. */', '#if %s' % guard, '']
    L.append('static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {')
    for i in range(0, len(bitmap), 16):
        L.append('    ' + ', '.join('0x%02x' % b for b in bitmap[i:i + 16]) + ',')
    L += ['};', '',
          'static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {',
          '    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */,']
    for i, (bi, adv, bw, bh, ox, oy, rid) in enumerate(dscs):
        L.append('    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, '
                 '.ofs_y = %d}, /* U+%04X %s */' % (bi, adv, bw, bh, ox, oy, PUA_BASE + i, rid))
    L += ['};', '',
          'static const lv_font_fmt_txt_cmap_t cmaps[] = {',
          '    {',
          '        .range_start = %d, .range_length = %d, .glyph_id_start = 1,'
          % (PUA_BASE, len(dscs)),
          '        .unicode_list = NULL, .glyph_id_ofs_list = NULL,',
          '        .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY',
          '    }',
          '};', '',
          'static lv_font_fmt_txt_glyph_cache_t cache;',
          'static const lv_font_fmt_txt_dsc_t font_dsc = {',
          '    .glyph_bitmap = glyph_bitmap,',
          '    .glyph_dsc = glyph_dsc,',
          '    .cmaps = cmaps,',
          '    .kern_dsc = NULL,',
          '    .kern_scale = 0,',
          '    .cmap_num = 1,',
          '    .bpp = 4,',
          '    .kern_classes = 0,',
          '    .bitmap_format = 0,',
          '    .cache = &cache',
          '};', '',
          '/* Line metrics copied from Montserrat %d: the font only ever serves as a fallback' % size,
          ' * behind it, and LVGL positions a fallback glyph on the MAIN font\'s baseline. */',
          'const lv_font_t %s = {' % sym,
          '    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,',
          '    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,',
          '    .line_height = %d,' % ref['line_height'],
          '    .base_line = %d,' % ref['base_line'],
          '    .subpx = LV_FONT_SUBPX_NONE,',
          '    .underline_position = %d,' % (-(size // 10)),
          '    .underline_thickness = %d,' % max(1, size // 24),
          '    .dsc = &font_dsc,',
          '    .fallback = NULL,',
          '    .user_data = NULL,',
          '};', '']
    if guard:
        L += ['#endif /* %s */' % guard, '']
    return '\n'.join(L), len(bitmap)


def emit_header(sizes):
    L = ['/* GENERATED by tools/gen_icons.py - DO NOT EDIT; run  python tools/gen_icons.py',
         ' * OpenBridge icon trial: this file belongs to the trial (see ICONS-TRIAL.md).',
         ' *',
         ' * Code points of the OpenBridge icons in the Private Use Area, as UTF-8 string',
         ' * literals, and the icon fonts. This header holds no artwork (MIT); the glyphs are',
         ' * in ob_icons_<px>.c (CC BY 4.0).',
         ' *',
         ' * Each macro is ONE string literal of three \\xNN escapes. Hex escapes are greedy,',
         ' * so never glue a hex digit directly onto one inside the same literal: write',
         ' * OB_ICON_ALARM " 5 m" (two literals), never "\\xEE\\x80\\x96" "5" merged by hand.',
         ' */',
         '#pragma once',
         '#ifdef LV_LVGL_H_INCLUDE_SIMPLE',
         '    #include "lvgl.h"',
         '#else',
         '    #include "lvgl/lvgl.h"',
         '#endif',
         '']
    for i, (macro, rid) in enumerate(PANEL_ICONS):
        b = chr(PUA_BASE + i).encode('utf-8')
        lit = ''.join('\\x%02X' % c for c in b)
        L.append('#define OB_ICON_%-14s "%s"   /* U+%04X %s */' % (macro, lit, PUA_BASE + i, rid))
    L += ['', '#define OB_ICON_COUNT %d' % len(PANEL_ICONS), '',
          '/* Icon font sizes compiled into this board (pixel sizes of the font roles). */',
          '#if defined(BOARD_PANEL_1024X600)',
          '#define OB_ICON_SIZES(X) ' + ' '.join('X(%d)' % s for s in SIZES_BIG),
          '#else',
          '#define OB_ICON_SIZES(X) ' + ' '.join('X(%d)' % s for s in SIZES_SMALL),
          '#endif', '']
    for s in sizes:
        L.append('LV_FONT_DECLARE(ob_icons_%d)' % s)
    L.append('')
    return '\n'.join(L)


# ── the web sprite ───────────────────────────────────────────────────────────

def sprite_block(src, icons):
    attribution = ('Icons: "%s" by %s, %s, %s %s, exported %s. Changes: %s. '
                   'Icons whose id ends in -google are based on Google Material Icons (Google '
                   'LLC, Apache-2.0); icons whose id ends in -iec are OpenBridge redrawings of '
                   'IEC 62288 symbols (no IEC rights granted). Not affiliated with or endorsed '
                   'by OpenBridge. OpenBridge icon trial.'
                   % (src.get('title', 'OpenBridge Icon Pack'), src.get('author', 'OpenBridge'),
                      src.get('url', ''), src.get('licence', 'CC BY 4.0'),
                      src.get('licenceUrl', ''), src.get('exportDate', '?'), CHANGES_WEB))
    if '--' in attribution:
        raise SystemExit('attribution text must not contain "--" (HTML comment)')
    lines = [SPRITE_BEGIN,
             '<svg xmlns="http://www.w3.org/2000/svg" id="%s" width="0" height="0" '
             'style="position:absolute;width:0;height:0;overflow:hidden" aria-hidden="true" '
             'focusable="false">' % SPRITE_ELEMENT_ID,
             '<!-- %s -->' % attribution]
    for rid in WEB_ICONS:
        vb, kids = icons[rid]
        lines.append('<symbol id="%s%s" viewBox="%s">%s</symbol>'
                     % (SYMBOL_PREFIX, rid, vb, ''.join(serialise(k) for k in kids)))
    lines += ['</svg>', SPRITE_END]
    text = '\n'.join(lines)
    if any(ord(c) > 127 for c in text):
        raise SystemExit('sprite must be plain ASCII')
    return text


def splice_sprite(html, block):
    a, b = html.find(SPRITE_BEGIN), html.find(SPRITE_END)
    if a < 0 or b < 0 or b < a:
        raise SystemExit('ERROR: data/index.html has no sprite markers. Put the two lines\n  %s\n'
                         '  %s\nright after <body>, then run again.' % (SPRITE_BEGIN, SPRITE_END))
    return html[:a] + block + html[b + len(SPRITE_END):]


# ── preview ──────────────────────────────────────────────────────────────────

def write_preview(path, per_size):
    from PIL import Image, ImageDraw
    sizes = sorted(per_size)
    cell = max(sizes) + 16
    img = Image.new('RGB', (len(PANEL_ICONS) * cell + 120, len(sizes) * cell + 8), (255, 255, 255))
    dr = ImageDraw.Draw(img)
    for si, size in enumerate(sizes):
        y0 = 4 + si * cell
        dr.text((4, y0 + cell // 2 - 6), '%d px' % size, fill=(0, 0, 0))
        ref, glyphs = per_size[size]
        base = y0 + cell - 8                           # baseline of this row
        for gi, (adv, bw, bh, ox, oy, rows) in enumerate(glyphs):
            x0 = 120 + gi * cell
            dr.rectangle([x0, base - ref['line_height'] + ref['base_line'],
                          x0 + adv // 16 - 1, base + ref['base_line'] - 1], outline=(220, 220, 255))
            for r, row in enumerate(rows):
                for c, v in enumerate(row):
                    if v:
                        g = 255 - v * 17
                        img.putpixel((x0 + ox + c, base - oy - bh + r), (g, g, g))
    img.save(path)


# ── main ─────────────────────────────────────────────────────────────────────

def main(argv=None):
    ap = argparse.ArgumentParser(description='OpenBridge icon trial: build the icon fonts and '
                                             'the web sprite.')
    ap.add_argument('--export', help='Figma export JSON (outside the repo); default: '
                                     '$OPENBRIDGE_EXPORT or ../Provenance/OpenBridge/')
    ap.add_argument('--map', default=DEFAULT_MAP, help='shared mapping file')
    ap.add_argument('--check', action='store_true',
                    help='do not write; exit 1 if any output differs from what would be written')
    ap.add_argument('--preview', metavar='PNG', help='also write a contact sheet of every glyph')
    ap.add_argument('--verbose', action='store_true', help='also print the per-icon notes')
    args = ap.parse_args(argv)
    try:
        sys.stdout.reconfigure(encoding='utf-8')
    except Exception:
        pass

    export, tried = find_export(args.export)
    if not export:
        print('ERROR: Figma export not found. Tried:\n  ' + '\n  '.join(tried))
        return 2

    rep = Report()
    panel_ids = [rid for _m, rid in PANEL_ICONS]
    mp, icons = load_icons(export, args.map, panel_ids + WEB_ICONS, rep)
    shapes = {}
    for rid in panel_ids:
        if rid in icons:
            try:
                shapes[rid] = icon_shapes(rid, icons[rid][1])
            except IconError as ex_:
                rep.error(rid, str(ex_))
    if args.verbose:
        for n in rep.notes:
            print('  note: ' + n)
    for w in rep.warnings:
        print('WARNING: ' + w)
    for e in rep.errors:
        print('ERROR: ' + e)
    if rep.errors:
        print('%d error(s): nothing written.' % len(rep.errors))
        return 1
    src = mp.get('source', {})

    outputs = collections.OrderedDict()
    per_size, total = {}, {}
    sizes = sorted(set(SIZES_SMALL) | set(SIZES_BIG))
    for size in sizes:
        ref = montserrat_reference(size)
        glyphs = []
        for rid in panel_ids:
            vb = [float(v) for v in icons[rid][0].split()]
            try:
                glyphs.append(make_glyph(rid, vb, shapes[rid], size, ref))
            except IconError as ex_:
                print('ERROR: %s: %s' % (rid, ex_))
                return 1
        text, nbytes = emit_font(size, ref, glyphs, src)
        outputs[os.path.join(FONT_DIR, 'ob_icons_%d.c' % size)] = text
        per_size[size] = (ref, glyphs)
        total[size] = nbytes
    outputs[HEADER_OUT] = emit_header(sizes)
    with open(INDEX_HTML, encoding='utf-8') as f:
        html = f.read()
    outputs[INDEX_HTML] = splice_sprite(html, sprite_block(src, icons))

    for size, rid, shifted, dropped in FIT_LOG:
        msg = '%s at %d px: kept inside its cell (shifted %d px, dropped edge up to %d/15)'             % (rid, size, shifted, dropped)
        if dropped >= 15:
            print('WARNING: ' + msg + ' - a SOLID pixel was cut off')
        elif args.verbose:
            print('  note: ' + msg)
    print('icons: %d panel, %d web; sizes: %s' % (len(PANEL_ICONS), len(WEB_ICONS),
                                                  ' '.join(str(s) for s in sizes)))
    for label, set_ in (('4-inch', SIZES_SMALL), ('1024x600', SIZES_BIG)):
        print('glyph data %-9s %6d bytes (%s)' % (label, sum(total[s] for s in set_),
                                                ' + '.join('%d' % total[s] for s in set_)))

    stale = []
    for path, text in outputs.items():
        data = text.encode('utf-8')
        try:
            with open(path, 'rb') as f:
                old = f.read().replace(b'\r\n', b'\n')
        except OSError:
            old = None
        if old == data:
            continue
        if args.check:
            stale.append(path)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'wb') as f:
                f.write(data)
            print('written: %s' % os.path.relpath(path, REPO))
    if args.preview:
        write_preview(args.preview, per_size)
        print('preview: %s' % args.preview)
    if args.check:
        for p in stale:
            print('STALE: %s' % os.path.relpath(p, REPO))
        print('up to date' if not stale else '%d file(s) stale' % len(stale))
        return 1 if stale else 0
    return 0


if __name__ == '__main__':
    sys.exit(main())
