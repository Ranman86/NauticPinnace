#!/usr/bin/env python3
"""
gen_icons.py - OpenBridge icon trial: builds NauticPinnace's icon fonts and web sprite.

    python tools/gen_icons.py [--export PATH] [--map PATH] [--check] [--preview PNG] [--verbose]

WHAT IT DOES
Reads the mapping file shared with NauticPi (tools/icons/openbridge-map.json, one entry
per icon) and the Figma export of the "OpenBridge Icon Pack" (CC BY 4.0), turns the icons
the firmware uses into single-colour shapes and writes:

  src/display/fonts/ob_icons_<px>.c   one 4-bpp LVGL bitmap font per pixel size
  src/display/fonts/ob_icons.h        code points (OB_ICON_*) and font declarations
  data/index.html                     the inline <svg> sprite between the BEGIN/END markers

WHERE THE EXPORT LIVES
Outside the repository: it also contains the OpenBridge logos and must never be
committed. Pass --export, set OPENBRIDGE_EXPORT, or keep it at
<parent of this repo>/Provenance/OpenBridge/openbridge-figma-export.json.

HOW AN ICON BECOMES SINGLE-COLOUR
Exactly as in NauticPi: the resolving and normalising code below is taken unchanged from
NauticPi's tools/gen_icons.py (same author), so both products draw the same shapes.

HOW IT BECOMES A FONT
The firmware cannot draw SVG (LVGL 8.4 has no vector decoder), so every icon is
rasterised here, at build time, into a glyph of a 4-bpp LVGL font in the Unicode Private
Use Area (from U+E000, in the order of PANEL_ICONS). The rasteriser is our own and small
on purpose:

- It fills each path with ITS OWN fill rule. Half of the icons use fill-rule="evenodd";
  a TrueType/FreeType route fills nonzero and closes their holes (anchor ring, depth
  marks, the "!" of the alarm). Filling per rule needs no outline surgery.
- Several paths of one icon are UNITED per sub-scanline before coverage is summed, so two
  shapes that share an edge leave no seam (alpha compositing would give 0.75 there).
- Coverage is exact horizontally and 16x supersampled vertically, then rounded to 4 bpp.
- Anything a font glyph cannot express - strokes, partial opacity, clip paths, masks,
  transforms - is an ERROR, not an approximation: the firmware set uses none of it today,
  and an icon added later that does must fail here rather than look subtly wrong.

THE GLYPH BOX
Each icon is drawn on its own grid (24 units, weather 32), scaled so that the WHOLE grid
is as tall as LVGL's Font Awesome gear (U+F013) in the Montserrat font of the same size,
vertically centred on that gear, and given the gear's advance width - the panel
equivalent of an SVG icon at 1em on a web page, which is how NauticPi shows them. An
earlier version scaled the grid's working area (20 of 24 units) to the gear instead: it
matched Font Awesome's visual weight, but the icons that use the full grid (sound-muted,
weather) then stood up to 4 px outside the advance and the line box, where LVGL clips
the label. Switching between the classic and the OpenBridge icons therefore moves
no label: widths and centre lines stay where they were. The Montserrat metrics are read
from the LVGL sources PlatformIO fetched (.pio/libdeps/*/lvgl), so build once first.

The output is deterministic: the same inputs give the same bytes. --check compares
instead of writing and exits 1 when anything on disk is stale.

Python 3 standard library only (PIL optional, for --preview). The script is MIT like the
rest of NauticPinnace; the artwork it produces is CC BY 4.0 - see the header of each
generated font and THIRD-PARTY-NOTICES.md.

OpenBridge icon trial: this script belongs to the trial (see ICONS-TRIAL.md).
"""
