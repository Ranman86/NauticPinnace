def find_montserrat(size):
    pats = glob.glob(os.path.join(REPO, '.pio', 'libdeps', '*', 'lvgl', 'src', 'font',
                                  'lv_font_montserrat_%d.c' % size))
    if not pats:
        raise SystemExit('ERROR: lv_font_montserrat_%d.c not found under .pio/libdeps - build '
                         'the project once so PlatformIO fetches LVGL.' % size)
    return sorted(pats)[0]


def montserrat_reference(size, cp=REFERENCE_CP):
    """-> dict(line_height, base_line, adv_w, box_w, box_h, ofs_x, ofs_y) for code point cp."""
    with open(find_montserrat(size), encoding='utf-8', errors='replace') as f:
        src = f.read()
    m = re.search(r'glyph_dsc\[\]\s*=\s*\{(.*?)\n\};', src, re.S)
    dscs = re.findall(r'\{\.bitmap_index = (\d+), \.adv_w = (\d+), \.box_w = (\d+), '
                      r'\.box_h = (\d+), \.ofs_x = (-?\d+), \.ofs_y = (-?\d+)\}', m.group(1))
    lists = {}
    for name, body in re.findall(r'static const uint16_t (unicode_list_\d+)\[\] = \{(.*?)\};',
                                 src, re.S):
        lists[name] = [int(v, 0) for v in re.findall(r'0x[0-9a-fA-F]+|\d+', body)]
    gid = None
    for rs, rl, gs, ul in re.findall(
            r'\.range_start = (\d+), \.range_length = (\d+), \.glyph_id_start = (\d+),\s*'
            r'\.unicode_list = (\w+)', src):
        rs, rl, gs = int(rs), int(rl), int(gs)
        if not rs <= cp < rs + rl:
            continue
        if ul == 'NULL':
            gid = gs + (cp - rs)
        elif (cp - rs) in lists[ul]:
            gid = gs + lists[ul].index(cp - rs)
    if gid is None:
        raise SystemExit('ERROR: U+%04X not found in %s' % (cp, find_montserrat(size)))
    # dscs includes the reserved id-0 row (it matches the pattern too), so the glyph id
    # IS the index. An earlier dscs[gid - 1] read U+F011 (power) instead of the gear -
    # the same box at most sizes, one pixel off at 18.
    _bi, adv, bw, bh, ox, oy = (int(v) for v in dscs[gid])
    lh = int(re.search(r'\.line_height = (\d+)', src).group(1))
    bl = int(re.search(r'\.base_line = (\d+)', src).group(1))
    return dict(line_height=lh, base_line=bl, adv_w=adv, box_w=bw, box_h=bh, ofs_x=ox, ofs_y=oy)


def make_glyph(rid, view_box, shapes, size, ref):
    """-> (adv_w16, box_w, box_h, ofs_x, ofs_y, rows of 0..15 values)."""
    grid = max(view_box[2], view_box[3])
    side = float(ref['box_h'])                           # pixels the longer grid side spans
    scale = side / grid
    adv_px = ref['adv_w'] / 16.0
    centre_y = ref['ofs_y'] + ref['box_h'] / 2.0         # above the baseline
    core = int(math.ceil(side)) + 2                      # the grid plus 1 px per edge
    canvas_left = int(round(adv_px / 2.0 - core / 2.0))
    canvas_bottom = int(round(centre_y - core / 2.0))
    # A non-square grid is centred on its shorter axis, as the web sprite shows it
    # (preserveAspectRatio xMidYMid).
    off_x = (core - view_box[2] * scale) / 2.0
    off_y = (core - view_box[3] * scale) / 2.0
    # MARGIN more pixels all round, so geometry drawn a little outside its view box is
    # still rasterised - fit_into_cell() then decides, and reports, what stays.
    MARGIN = 3
    cov = rasterise(shapes, view_box, scale, -off_x, -off_y, core, core, pad=MARGIN)
    n = core + 2 * MARGIN
    canvas_left -= MARGIN
    canvas_bottom -= MARGIN
    vals = [[min(15, max(0, int(v * 15 + 0.5))) for v in row] for row in cov]
    nz_rows = [r for r in range(n) if any(vals[r])]
    nz_cols = [c for c in range(n) if any(vals[r][c] for r in range(n))]
    if not nz_rows:
        raise IconError('renders empty at %d px' % size)
    r0, r1, c0, c1 = nz_rows[0], nz_rows[-1], nz_cols[0], nz_cols[-1]
    box = [row[c0:c1 + 1] for row in vals[r0:r1 + 1]]
    ox, oy = canvas_left + c0, canvas_bottom + (n - 1 - r1)
    box, ox, oy = fit_into_cell(rid, size, box, ox, oy, int(adv_px),
                                ref['line_height'] - ref['base_line'], -ref['base_line'])
    return (ref['adv_w'], len(box[0]), len(box), ox, oy, box)


FIT_LOG = []


def fit_into_cell(rid, size, box, ox, oy, adv, top, bottom):
    """Keep the glyph inside [0, adv) x [bottom, top): the area of a label holding it.

    A few icons are drawn a hair beyond their view box, and integer placement adds the
    rest: they would stand up to one pixel outside, where LVGL clips the label anyway.
    Shift inward where the cell has room; where it has none, drop the outermost row or
    column ourselves, so the font shows exactly what the panel will show. Dropping more
    than anti-aliasing fringe is reported - that would be real shape lost."""
    bw, bh = len(box[0]), len(box)
    shifted, dropped = 0, 0
    # horizontal: shift first, then clip what still does not fit
    if ox < 0 and ox + bw < adv:
        s = min(-ox, adv - (ox + bw)); ox += s; shifted += s
    elif ox + bw > adv and ox > 0:
        s = min(ox + bw - adv, ox); ox -= s; shifted += s
    while ox < 0 and len(box[0]) > 1:
        dropped = max(dropped, max(r[0] for r in box)); box = [r[1:] for r in box]; ox += 1
    while ox + len(box[0]) > adv and len(box[0]) > 1:
        dropped = max(dropped, max(r[-1] for r in box)); box = [r[:-1] for r in box]
    # vertical: oy is the bottom edge above the baseline, box[0] is the top row
    bh = len(box)
    if oy < bottom and oy + bh < top:
        s = min(bottom - oy, top - (oy + bh)); oy += s; shifted += s
    elif oy + bh > top and oy > bottom:
        s = min(oy + bh - top, oy - bottom); oy -= s; shifted += s
    while oy < bottom and len(box) > 1:
        dropped = max(dropped, max(box[-1])); box = box[:-1]; oy += 1
    while oy + len(box) > top and len(box) > 1:
        dropped = max(dropped, max(box[0])); box = box[1:]
    if shifted or dropped:
        FIT_LOG.append((size, rid, shifted, dropped))
    return box, ox, oy


def pack4(rows):
    out, acc, nbits = bytearray(), 0, 0
    for row in rows:
        for v in row:
            acc = (acc << 4) | v
            nbits += 4
            while nbits >= 8:
                nbits -= 8
                out.append((acc >> nbits) & 0xFF)
    if nbits:
        out.append((acc << (8 - nbits)) & 0xFF)
    return bytes(out)


