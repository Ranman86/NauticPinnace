# ── numbers and path data ────────────────────────────────────────────────────

NUM_RE = re.compile(r'[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?')
NAN_RE = re.compile(r'nan|inf', re.IGNORECASE)
PATH_ARGS = {'M': 2, 'L': 2, 'H': 1, 'V': 1, 'C': 6, 'S': 4, 'Q': 4, 'T': 2, 'A': 7, 'Z': 0}


def fmt(value, decimals=2):
    """Shortest text for a number rounded to `decimals`: 0.50 -> .5, -0.00 -> 0."""
    s = '%.*f' % (decimals, value)
    if '.' in s:
        s = s.rstrip('0').rstrip('.')
    if s in ('-0', '', '-'):
        s = '0'
    if float(s) == 0:
        return '0'
    if s.startswith('0.'):
        s = s[1:]
    elif s.startswith('-0.'):
        s = '-' + s[2:]
    return s


def round_numbers(text, decimals=2):
    return NUM_RE.sub(lambda m: fmt(float(m.group()), decimals), text)


def parse_path(d):
    """Path data -> [(command, [[numbers], ...])]; implicit repeats become extra groups."""
    if NAN_RE.search(d):
        raise IconError("path data contains NaN/Inf (Figma export bug): %r" % d[:80])
    segs, i, n = [], 0, len(d)

    def skip(j):
        while j < n and (d[j].isspace() or d[j] == ','):
            j += 1
        return j

    while True:
        i = skip(i)
        if i >= n:
            break
        c = d[i]
        if not c.isalpha() or c.upper() not in PATH_ARGS:
            raise IconError('unexpected %r at %d in path data' % (c, i))
        i += 1
        k = PATH_ARGS[c.upper()]
        groups = []
        if k:
            while True:
                grp = []
                for j in range(k):
                    i = skip(i)
                    if c.upper() == 'A' and j in (3, 4):
                        if i < n and d[i] in '01':
                            grp.append(float(d[i]))
                            i += 1
                            continue
                        break
                    m = NUM_RE.match(d, i)
                    if not m:
                        break
                    grp.append(float(m.group()))
                    i = m.end()
                if len(grp) != k:
                    raise IconError('command %s needs %d numbers, found %d' % (c, k, len(grp)))
                groups.append(grp)
                j = skip(i)
                if j >= n or not (d[j].isdigit() or d[j] in '+-.'):
                    break
        segs.append((c, groups))
    if segs and segs[0][0] not in 'Mm':
        raise IconError('path data does not start with a moveto')
    return segs


def format_path(segs):
    out = []
    for cmd, groups in segs:
        out.append(cmd)
        last = None
        for grp in groups:
            for j, v in enumerate(grp):
                s = ('1' if v else '0') if (cmd in 'Aa' and j in (3, 4)) else fmt(v)
                if last is not None and not s.startswith('-'):
                    out.append(' ')
                out.append(s)
                last = s
    return ''.join(out)


def rect_to_segments(el):
    x, y = float(el.get('x', 0)), float(el.get('y', 0))
    w, h = float(el.get('width', 0)), float(el.get('height', 0))
    if el.get('rx') or el.get('ry'):
        raise IconError('rounded rect cannot be cut out as a hole')
    return [('M', [[x, y]]), ('H', [[x + w]]), ('V', [[y + h]]), ('H', [[x]]), ('Z', [])]


# ── colours ──────────────────────────────────────────────────────────────────

NAMED_COLOURS = {'white': (255, 255, 255), 'black': (0, 0, 0)}


def parse_colour(v):
    lv = v.strip().lower()
    if lv in NAMED_COLOURS:
        return NAMED_COLOURS[lv]
    m = re.fullmatch(r'#([0-9a-f])([0-9a-f])([0-9a-f])', lv)
    if m:
        return tuple(int(g * 2, 16) for g in m.groups())
    m = re.fullmatch(r'#([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})(?:[0-9a-f]{2})?', lv)
    if m:
        return tuple(int(g, 16) for g in m.groups())
    m = re.fullmatch(r'rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,[^)]*)?\)', lv)
    if m:
        return tuple(int(g) for g in m.groups())
    return None


def paint_kind(v):
    """none | current | url | white | light-grey | light | dark | unknown"""
    if v is None:
        return 'none'
    lv = v.strip().lower()
    if lv in ('none', 'transparent', ''):
        return 'none'
    if lv == 'currentcolor':
        return 'current'
    if lv.startswith('url('):
        return 'url'
    rgb = parse_colour(v)
    if rgb is None:
        return 'unknown'
    if rgb == (255, 255, 255):
        return 'white'
    luma = (0.299 * rgb[0] + 0.587 * rgb[1] + 0.114 * rgb[2]) / 255.0
    if luma > LIGHT_LUMA:
        return 'light-grey' if max(rgb) - min(rgb) <= GREY_CHROMA else 'light'
    return 'dark'


# ── resolving map entries against the export ─────────────────────────────────

def sanitise(name):
    s = unicodedata.normalize('NFC', name)
    for a, b in (('å', 'aa'), ('æ', 'ae'), ('ø', 'oe'), ('Å', 'aa'), ('Æ', 'ae'), ('Ø', 'oe')):
        s = s.replace(a, b)
    return re.sub(r'\s+', '', s).replace('%', '').lower()


def nearest_frame(item):
    frames = [p.strip() for p in (item.get('path') or [])
              if p.strip().lower() not in ('outlined', 'filled')]
    return frames[-1] if frames else None


class ExportIndex:
    def __init__(self, items):
        self.by_node = {}
        self.by_name = collections.defaultdict(list)
        self.by_sanitised = collections.defaultdict(list)
        self.by_frame = collections.defaultdict(list)
        for it in items:
            self.by_node[it['id']] = it
            self.by_name[it['name']].append(it)
            self.by_sanitised[sanitise(it['name'])].append(it)
            frame = nearest_frame(it)
            if frame:
                self.by_frame[frame].append(it)

    def resolve(self, entry):
        """-> (item, how). Raises IconError when nothing or more than one component fits."""
        rid, figma, node = entry['id'], entry.get('figma'), entry.get('node')
        if node:
            it = self.by_node.get(node)
            if it is None:
                raise IconError('node %s is not in the export' % node)
            return it, 'node'
        steps = (('name', self.by_name, figma or rid),
                 ('name', self.by_name, rid),
                 ('sanitised', self.by_sanitised, sanitise(figma or rid)),
                 ('sanitised', self.by_sanitised, sanitise(rid)),
                 ('frame', self.by_frame, rid))
        for how, table, key in steps:
            cands = table.get(key) or []
            if len(cands) == 1:
                return cands[0], how
            if len(cands) > 1:
                raise IconError('%s %r is ambiguous (%s); give "node" in the map'
                                % (how, key, ', '.join(c['id'] for c in cands)))
        raise IconError('no Figma component found')


# ── converting one icon ──────────────────────────────────────────────────────

def local(tag):
    return tag.split('}', 1)[1] if tag.startswith('{') else tag


def attr_name(name):
    if name.startswith('{%s}' % XLINK_NS):
        return 'href'
    return local(name)


def normalise_attrs(el):
    """Plain attribute dict (xlink:href -> href; style="a:b" -> attributes)."""
    attrs = collections.OrderedDict()
    for k, v in el.attrib.items():
        attrs[attr_name(k)] = v
    style = attrs.pop('style', None)
    if style:
        for part in style.split(';'):
            if ':' in part:
                k, v = part.split(':', 1)
                attrs.setdefault(k.strip(), v.strip())
    return attrs


class Node:
    def __init__(self, tag, attrs, children=None):
        self.tag, self.attrs, self.children = tag, attrs, children or []


def convert_icon(icon_id, item, mono, rep):
    try:
        root = ET.fromstring(item['svg'])
    except ET.ParseError as ex:
        raise IconError('SVG does not parse: %s' % ex)
    if local(root.tag) != 'svg':
        raise IconError('root element is <%s>, not <svg>' % local(root.tag))
    rattrs = normalise_attrs(root)
    view_box = rattrs.get('viewBox') or '0 0 %s %s' % (fmt(item['w']), fmt(item['h']))
    if NAN_RE.search(view_box):
        raise IconError('viewBox contains NaN')
    view_box = round_numbers(view_box)

    ids = {}
    for el in root.iter():
        if 'id' in el.attrib:
            ids[el.attrib['id']] = '%s%s-%s' % (SYMBOL_PREFIX, icon_id, el.attrib['id'])

    def fix_refs(v):
        v = re.sub(r'url\(\s*#([^)\s]+)\s*\)',
                   lambda m: 'url(#%s)' % ids.get(m.group(1), m.group(1)), v)
        if v.startswith('#') and v[1:] in ids:
            v = '#' + ids[v[1:]]
        return v

    def round_attrs(attrs):
        for k in list(attrs):
            v = attrs[k]
            if NAN_RE.search(v) and k in NUMERIC_ATTRS | {'d', 'transform'}:
                raise IconError('attribute %s contains NaN: %r' % (k, v[:60]))
            if k == 'd':
                attrs[k] = format_path(parse_path(v))
            elif k == 'transform':
                attrs[k] = round_numbers(v, 4)
            elif k in NUMERIC_ATTRS:
                attrs[k] = round_numbers(v)
            elif k == 'id':
                attrs[k] = ids[v]
            else:
                attrs[k] = fix_refs(v)

    paint_notes = collections.Counter()

    def recolour(value, channel, attrs):
        """-> (new paint, opacity factor) or (None, None) to drop the channel."""
        kind = paint_kind(value)
        if kind == 'none':
            return 'none', 1.0
        if kind == 'current':
            return 'currentColor', 1.0
        if mono == 'flatten':
            return 'currentColor', 1.0
        if kind == 'url':
            rep.warn(icon_id, '%s=%s (a paint server) flattened to currentColor' % (channel, value))
            return 'currentColor', 1.0
        if kind == 'unknown':
            rep.warn(icon_id, '%s=%s is no known colour; treated as currentColor' % (channel, value))
            return 'currentColor', 1.0
        if kind in ('white', 'light', 'light-grey') and mono == 'drop-light':
            paint_notes['dropped light layer %s' % value] += 1
            return None, None
        if kind == 'white':
            return None, None      # the caller decides: hole or report
        if kind == 'light-grey':
            paint_notes['light grey %s -> currentColor at %s' % (value, fmt(LIGHT_OPACITY))] += 1
            return 'currentColor', LIGHT_OPACITY
        if kind == 'light':
            rep.warn(icon_id, 'light colour %s=%s flattened to currentColor (consider "mono")'
                     % (channel, value))
            return 'currentColor', 1.0
        return 'currentColor', 1.0

    def walk(el, inh_fill, inh_stroke, context):
        tag = local(el.tag)
        if tag in DROPPED_ELEMENTS:
            return None
        if tag == 'text' or tag == 'image' or tag == 'foreignObject':
            raise IconError('<%s> is not supported in an icon' % tag)
        if (el.text or '').strip() and tag not in ('style',):
            rep.warn(icon_id, 'text content in <%s> ignored' % tag)
        attrs = normalise_attrs(el)
        ctx = context
        if tag == 'clipPath':
            ctx = 'clip'
        elif tag == 'mask':
            ctx = 'mask'
        elif tag in PAINT_SERVERS or tag in ('filter', 'defs'):
            ctx = ctx if ctx in ('clip', 'mask') else 'defs'

        fill = attrs.get('fill', inh_fill)
        stroke = attrs.get('stroke', inh_stroke)
        round_attrs(attrs)

        if tag in SHAPES and ctx == 'draw':
            node = shape(tag, attrs, fill, stroke)
            return node
        if tag in SHAPES and ctx == 'clip':
            # Geometry only: paint inside a clipPath means nothing.
            for k in ('fill', 'stroke', 'fill-opacity', 'stroke-opacity', 'opacity'):
                attrs.pop(k, None)
            return Node(tag, attrs)
        if tag in SHAPES:
            return Node(tag, attrs)          # mask/defs content: colours kept (luminance)

        if tag in CONTAINERS and ctx == 'draw':
            attrs.pop('fill', None)
            attrs.pop('stroke', None)
        elif tag not in CONTAINERS and tag not in DEFS_LIKE and tag != 'use':
            rep.warn(icon_id, 'unexpected element <%s> kept as it is' % tag)
        kids = []
        for ch in el:
            n = walk(ch, fill, stroke, ctx)
            if n is not None:
                kids.append(n)
        return Node(tag, attrs, kids)

    def shape(tag, attrs, fill, stroke):
        attrs.pop('clip-rule', None)                     # only means something in a clipPath
        new_fill, fill_op = recolour(fill, 'fill', attrs)
        new_stroke, stroke_op = recolour(stroke, 'stroke', attrs)
        fill_white = paint_kind(fill) == 'white' and mono not in ('flatten', 'drop-light')
        stroke_white = paint_kind(stroke) == 'white' and mono not in ('flatten', 'drop-light')
        node = Node(tag, attrs)
        if fill_white:
            if mono == 'holes' and paint_kind(stroke) == 'none':
                node.hole = True
                return node
            rep.warn(icon_id, 'white fill on <%s> outside a clipPath dropped' % tag)
        if stroke_white:
            rep.warn(icon_id, 'white stroke on <%s> outside a clipPath dropped' % tag)
        if mono == 'holes' and paint_kind(fill) == 'none' and paint_kind(stroke) != 'none':
            paint_notes['stroke-only outline dropped'] += 1
            return None
        new_fill = new_fill or 'none'
        new_stroke = new_stroke or 'none'
        if new_fill == 'none' and new_stroke == 'none':
            paint_notes['unpainted <%s> dropped' % tag] += 1
            return None
        attrs['fill'] = new_fill
        attrs['stroke'] = new_stroke
        if new_fill == 'none':
            for k in FILL_ONLY_ATTRS:
                attrs.pop(k, None)
        elif fill_op is not None and fill_op < 1:
            attrs['fill-opacity'] = fmt(float(attrs.get('fill-opacity', 1)) * fill_op)
        if new_stroke == 'none':
            for k in STROKE_ONLY_ATTRS:
                attrs.pop(k, None)
        elif stroke_op is not None and stroke_op < 1:
            attrs['stroke-opacity'] = fmt(float(attrs.get('stroke-opacity', 1)) * stroke_op)
        return node

    kids = []
    for ch in root:
        n = walk(ch, rattrs.get('fill', 'black'), rattrs.get('stroke', 'none'), 'draw')
        if n is not None:
            kids.append(n)

    # "holes": cut white shapes out of the nearest filled path painted before them.
    def cut_holes(nodes):
        out, host = [], None
        for n in nodes:
            if getattr(n, 'hole', False):
                if host is None:
                    raise IconError('white shape without a filled shape below it')
                segs = parse_path(n.attrs['d']) if n.tag == 'path' else \
                    rect_to_segments(n.attrs) if n.tag == 'rect' else None
                if segs is None:
                    raise IconError('cannot cut a <%s> out as a hole' % n.tag)
                if segs[0][0] == 'm':
                    segs[0] = ('M', segs[0][1])     # a leading m is absolute by definition
                host.attrs['d'] = host.attrs['d'] + format_path(segs)
                host.attrs['fill-rule'] = 'evenodd'
                paint_notes['white shape cut out as a hole (evenodd)'] += 1
                continue
            n.children = cut_holes(n.children)
            if n.tag == 'path' and n.attrs.get('fill', 'none') != 'none':
                host = n
            elif n.tag == 'rect' and n.attrs.get('fill', 'none') != 'none' and mono == 'holes':
                n.tag, n.attrs['d'] = 'path', format_path(rect_to_segments(n.attrs))
                for k in ('x', 'y', 'width', 'height'):
                    n.attrs.pop(k, None)
                host = n
            out.append(n)
        return out

    kids = cut_holes(kids)
    if mono == 'holes' and not paint_notes['white shape cut out as a hole (evenodd)']:
        rep.warn(icon_id, 'mono "holes" found no white shape to cut out')
    for msg, cnt in sorted(paint_notes.items()):
        rep.note(icon_id, msg + (' (x%d)' % cnt if cnt > 1 else ''))
    if not kids:
        raise IconError('nothing left to draw')
    return view_box, kids


# ── serialising ──────────────────────────────────────────────────────────────

def esc(v):
    return v.replace('&', '&amp;').replace('<', '&lt;').replace('"', '&quot;')


def ordered(attrs):
    keys = [k for k in ATTR_ORDER if k in attrs] + [k for k in attrs if k not in ATTR_ORDER]
    return ''.join(' %s="%s"' % (k, esc(attrs[k])) for k in keys)


def serialise(node):
    if not node.children:
        return '<%s%s/>' % (node.tag, ordered(node.attrs))
    return '<%s%s>%s</%s>' % (node.tag, ordered(node.attrs),
                              ''.join(serialise(c) for c in node.children), node.tag)
