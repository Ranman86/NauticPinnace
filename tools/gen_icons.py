def _cubic(p0, p1, p2, p3, out):
    ctrl = (math.dist(p0, p1) + math.dist(p1, p2) + math.dist(p2, p3))
    n = max(4, min(96, int(math.ceil(ctrl * 4))))
    for i in range(1, n + 1):
        t = i / n
        a, b, c, d = (1 - t) ** 3, 3 * t * (1 - t) ** 2, 3 * t * t * (1 - t), t ** 3
        out.append((a * p0[0] + b * p1[0] + c * p2[0] + d * p3[0],
                    a * p0[1] + b * p1[1] + c * p2[1] + d * p3[1]))


def _quad(p0, p1, p2, out):
    ctrl = math.dist(p0, p1) + math.dist(p1, p2)
    n = max(4, min(96, int(math.ceil(ctrl * 4))))
    for i in range(1, n + 1):
        t = i / n
        a, b, c = (1 - t) ** 2, 2 * t * (1 - t), t * t
        out.append((a * p0[0] + b * p1[0] + c * p2[0], a * p0[1] + b * p1[1] + c * p2[1]))


def _arc(p1, rx, ry, phi_deg, fa, fs, p2, out):
    """SVG elliptical arc (implementation notes F.6.5) appended as line points."""
    x1, y1 = p1
    x2, y2 = p2
    if (x1, y1) == (x2, y2):
        return
    rx, ry = abs(rx), abs(ry)
    if rx == 0 or ry == 0:
        out.append((x2, y2))
        return
    phi = math.radians(phi_deg % 360)
    cp, sp = math.cos(phi), math.sin(phi)
    dx2, dy2 = (x1 - x2) / 2, (y1 - y2) / 2
    x1p = cp * dx2 + sp * dy2
    y1p = -sp * dx2 + cp * dy2
    lam = (x1p * x1p) / (rx * rx) + (y1p * y1p) / (ry * ry)
    if lam > 1:
        s = math.sqrt(lam)
        rx, ry = rx * s, ry * s
    num = rx * rx * ry * ry - rx * rx * y1p * y1p - ry * ry * x1p * x1p
    den = rx * rx * y1p * y1p + ry * ry * x1p * x1p
    coef = math.sqrt(max(0.0, num / den)) if den else 0.0
    if fa == fs:
        coef = -coef
    cxp = coef * rx * y1p / ry
    cyp = -coef * ry * x1p / rx
    cx = cp * cxp - sp * cyp + (x1 + x2) / 2
    cy = sp * cxp + cp * cyp + (y1 + y2) / 2

    def ang(ux, uy, vx, vy):
        return math.atan2(ux * vy - uy * vx, ux * vx + uy * vy)

    ux, uy = (x1p - cxp) / rx, (y1p - cyp) / ry
    vx, vy = (-x1p - cxp) / rx, (-y1p - cyp) / ry
    th1 = ang(1, 0, ux, uy)
    dth = ang(ux, uy, vx, vy)
    if not fs and dth > 0:
        dth -= 2 * math.pi
    elif fs and dth < 0:
        dth += 2 * math.pi
    n = max(4, min(128, int(math.ceil(abs(dth) * max(rx, ry) * 4))))
    for i in range(1, n + 1):
        a = th1 + dth * i / n
        ca, sa = math.cos(a), math.sin(a)
        out.append((cx + rx * ca * cp - ry * sa * sp, cy + rx * ca * sp + ry * sa * cp))
    out[-1] = (x2, y2)                        # land exactly on the end point


def path_polygons(d):
    """Path data -> list of closed polygons (point lists) in user units."""
    polys, cur = [], None
    x = y = sx = sy = 0.0
    last_cmd, last_ctrl = '', None
    for cmd, groups in parse_path(d):
        C, rel = cmd.upper(), cmd.islower()
        if C == 'Z':
            if cur:
                polys.append(cur)
            cur = None
            x, y = sx, sy
            last_cmd, last_ctrl = 'Z', None
            continue
        for gi, g in enumerate(groups):
            ox, oy = (x, y) if rel else (0.0, 0.0)
            if C == 'M' and gi == 0:
                if cur:
                    polys.append(cur)           # an unclosed subpath is filled closed
                x, y = ox + g[0], oy + g[1]
                cur, sx, sy = [(x, y)], x, y
                last_cmd, last_ctrl = 'M', None
                continue
            if cur is None:                     # drawing right after Z: start at (x, y)
                cur, sx, sy = [(x, y)], x, y
            if C in ('M', 'L'):                 # extra M pairs are implicit linetos
                x, y = ox + g[0], oy + g[1]
                cur.append((x, y))
                last_ctrl = None
            elif C == 'H':
                x = ox + g[0]
                cur.append((x, y))
                last_ctrl = None
            elif C == 'V':
                y = oy + g[0]
                cur.append((x, y))
                last_ctrl = None
            elif C == 'C':
                c1 = (ox + g[0], oy + g[1])
                c2 = (ox + g[2], oy + g[3])
                p = (ox + g[4], oy + g[5])
                _cubic((x, y), c1, c2, p, cur)
                (x, y), last_ctrl = p, c2
            elif C == 'S':
                c1 = (2 * x - last_ctrl[0], 2 * y - last_ctrl[1]) \
                    if last_cmd in ('C', 'S') and last_ctrl else (x, y)
                c2 = (ox + g[0], oy + g[1])
                p = (ox + g[2], oy + g[3])
                _cubic((x, y), c1, c2, p, cur)
                (x, y), last_ctrl = p, c2
            elif C == 'Q':
                c = (ox + g[0], oy + g[1])
                p = (ox + g[2], oy + g[3])
                _quad((x, y), c, p, cur)
                (x, y), last_ctrl = p, c
            elif C == 'T':
                c = (2 * x - last_ctrl[0], 2 * y - last_ctrl[1]) \
                    if last_cmd in ('Q', 'T') and last_ctrl else (x, y)
                p = (ox + g[0], oy + g[1])
                _quad((x, y), c, p, cur)
                (x, y), last_ctrl = p, c
            elif C == 'A':
                p = (ox + g[5], oy + g[6])
                _arc((x, y), g[0], g[1], g[2], int(g[3]), int(g[4]), p, cur)
                (x, y), last_ctrl = p, None
            last_cmd = C
    if cur:
        polys.append(cur)
    return [p for p in polys if len(p) >= 3]


# ── rasterising ──────────────────────────────────────────────────────────────

FONT_UNSUPPORTED_ATTRS = ('transform', 'clip-path', 'mask', 'opacity', 'fill-opacity',
                          'stroke-opacity')


def icon_shapes(rid, kids):
    """Normalised node tree -> [(polygons, rule)]. Refuses what a glyph cannot hold."""
    shapes = []

    def walk(n):
        for k in FONT_UNSUPPORTED_ATTRS:
            if k in n.attrs:
                raise IconError('%s on <%s> cannot be expressed in a font glyph' % (k, n.tag))
        if n.tag == 'g':
            for c in n.children:
                walk(c)
            return
        if n.tag in ('defs', 'clipPath', 'mask'):
            raise IconError('<%s> cannot be expressed in a font glyph' % n.tag)
        if n.tag != 'path':
            raise IconError('<%s> is not supported by the font rasteriser yet' % n.tag)
        if n.attrs.get('stroke', 'none') != 'none':
            raise IconError('a stroked path cannot be expressed in a font glyph yet')
        if n.attrs.get('fill', 'none') == 'none':
            return
        rule = n.attrs.get('fill-rule', 'nonzero')
        if rule not in ('nonzero', 'evenodd'):
            raise IconError('unknown fill-rule %r' % rule)
        shapes.append((path_polygons(n.attrs['d']), rule))

    for k in kids:
        walk(k)
    if not shapes:
        raise IconError('no filled path')
    return shapes


def rasterise(shapes, view_box, scale, left, top, w, h, pad=0):
    """Coverage grid ((h + 2 pad) rows x (w + 2 pad) cols, 0..1) of the united shapes.

    User point (ux, uy) lands on pixel coordinate ((ux - vx) * scale - left,
    (uy - vy) * scale - top); pixel (c, r) covers [c, c+1) x [r, r+1), for c and r
    from -pad to w + pad - 1, stored at [r + pad][c + pad].

    The pad widens the grid by INTEGER indices only. Shifting the coordinates instead
    (left - pad) would move every point by an ulp, and coverage values that sit exactly
    on a 4-bit step would flip - measured: a 3 px wider canvas changed bitmaps at 24 and
    48 px and, through Python's round-half-to-even, offsets at 12 and 14 px."""
    vx, vy = view_box[0], view_box[1]
    paths = []
    for polys, rule in shapes:
        edges = []
        for poly in polys:
            pts = [((px - vx) * scale - left, (py - vy) * scale - top) for px, py in poly]
            for i in range(len(pts)):
                x0, y0 = pts[i]
                x1, y1 = pts[(i + 1) % len(pts)]
                if y0 != y1:
                    edges.append((x0, y0, x1, y1))
        # Bucket edges by pixel row so each sub-scanline only tests a handful.
        rows = [[] for _ in range(h + 2 * pad)]
        for e in edges:
            lo, hi = min(e[1], e[3]), max(e[1], e[3])
            for r in range(max(-pad, int(math.floor(lo))), min(h + pad, int(math.ceil(hi)))):
                rows[r + pad].append(e)
        paths.append((rows, rule))

    W = w + 2 * pad
    cov = [[0.0] * W for _ in range(h + 2 * pad)]
    wgt = 1.0 / SUBSAMPLES
    for r in range(-pad, h + pad):
        row = cov[r + pad]
        for s in range(SUBSAMPLES):
            y = r + (s + 0.5) / SUBSAMPLES
            spans = []
            for rows, rule in paths:
                xs = []
                for x0, y0, x1, y1 in rows[r + pad]:
                    if y0 <= y < y1:
                        xs.append((x0 + (y - y0) * (x1 - x0) / (y1 - y0), 1))
                    elif y1 <= y < y0:
                        xs.append((x0 + (y - y0) * (x1 - x0) / (y1 - y0), -1))
                if not xs:
                    continue
                xs.sort()
                if rule == 'evenodd':
                    for i in range(0, len(xs) - 1, 2):
                        spans.append((xs[i][0], xs[i + 1][0]))
                else:
                    wind, start = 0, None
                    for xv, dv in xs:
                        before = wind
                        wind += dv
                        if before == 0 and wind != 0:
                            start = xv
                        elif before != 0 and wind == 0:
                            spans.append((start, xv))
            if not spans:
                continue
            spans.sort()
            merged = [list(spans[0])]
            for a, b in spans[1:]:
                if a <= merged[-1][1]:
                    if b > merged[-1][1]:
                        merged[-1][1] = b
                else:
                    merged.append([a, b])
            for a, b in merged:
                a, b = max(float(-pad), a), min(float(w + pad), b)
                if b <= a:
                    continue
                ia, ib = int(math.floor(a)), int(math.floor(b))
                if ia == ib:
                    row[ia + pad] += (b - a) * wgt
                    continue
                row[ia + pad] += (ia + 1 - a) * wgt
                for c in range(ia + 1, ib):
                    row[c + pad] += wgt
                if ib < w + pad:
                    row[ib + pad] += (b - ib) * wgt
    return cov


